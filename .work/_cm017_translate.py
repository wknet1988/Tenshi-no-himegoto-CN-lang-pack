SKIP = set()


def main():
    orig = Script(open(os.path.join('.work', 'extract', 'CM017'), 'rb').read(),
                  encoding='cp932')
    work = [i for i, s in enumerate(orig.strings) if KANA.search(s)]
    out = {}
    for i in work:
        if i in T:
            out['CM017#%d' % i] = wrap(orig.strings[i], T[i])
    missing = [i for i in work if i not in SKIP and i not in T]
    if missing:
        print('!! 未提供译文下标:', missing[:20])
        sys.exit(1)
    for i in T:
        if i not in work:
            print('!! 多余条目(不可译或不存在): #%d' % i)
            sys.exit(1)
    os.makedirs(ZH_DIR, exist_ok=True)
    json.dump(out, open(os.path.join(ZH_DIR, 'CM017.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print('目标条数: %d | 已写出: %d' % (len(work), len(out)))
    from to_jp import drawable, MERGED
    sus = {}
    for v in out.values():
        for ch in v:
            if '一' <= ch <= '鿿' and not drawable(ch):
                sus[ch] = sus.get(ch, 0) + 1
    bad = [(c, MERGED.get(c)) for c in sorted(sus) if not MERGED.get(c)]
    print('需映射字: %d；无解: %s' % (len(sus), bad or '无'))
    for c in sorted(sus):
        print('   ', c, '->', MERGED.get(c), sus[c])


if __name__ == '__main__':
    main()
