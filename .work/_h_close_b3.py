BAD = {'分', '那', '務', '察', '足', '走', '愚', '様', '怪', '助', '機', '辺', '捻', '諍',
       '殴', '菓', '嘘', '狙', '任', '投', '立', '細', '開', '留', '首', '接'}


def main():
    sys.path.insert(0, '.work')
    from to_jp import MERGED, drawable
    bad = [(k, c) for k, v in T.items() for c in v
           if c not in '　「」…。、？！ー・ッふぅあやはくっ' and not drawable(c) and c not in MERGED]
    print('无解字:', sorted(set(c for _, c in bad)) or '无')
    warn = [(k, c, MERGED[c]) for k, v in T.items() for c in v if c in MERGED and MERGED[c] in BAD]
    print('坏映射告警:', warn or '无')
    files = {}
    for k in T:
        files.setdefault(k.split('#')[0], []).append(k)
    for name, ks in files.items():
        o = Script(open(os.path.join('.work', 'extract', name), 'rb').read(), encoding='cp932')
        out = {k: wrap(o.strings[int(k.split('#')[1])], T[k]) for k in ks}
        json.dump(out, open(os.path.join(ZH, name + '.json'), 'w', encoding='utf-8'),
                  ensure_ascii=False, indent=1)
        print('%s -> %d' % (name, len(out)))


if __name__ == '__main__':
    main()
