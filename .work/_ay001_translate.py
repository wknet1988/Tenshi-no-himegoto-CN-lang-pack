# ---------- 组装：保留原控制符骨架 ----------
def split_orig(s):
    if '\x01' in s:
        pre, post = s.split('\x01', 1)
        prefix = pre + '\x01'
        if post.startswith('\u3000'):
            prefix += '\u3000'
            post = post[1:]
    else:
        prefix, post = '', s
    suf = ''
    while post and ord(post[-1]) < 0x20:
        suf = post[-1] + suf
        post = post[:-1]
    return prefix, post, suf

def ctrl_seq(s):
    return [c for c in s if ord(c) < 0x20]

out = {}
bad = []
for i in target:
    prefix, body, suf = split_orig(orig.strings[i])
    val = prefix + TR[i] + suf
    o = orig.strings[i]
    if ctrl_seq(val) != ctrl_seq(o):
        bad.append((i, '控制符不一致', repr(o), repr(val)))
    if not TR[i].strip():
        bad.append((i, '译文为空'))
    out['AY001#%d' % i] = val

if bad:
    print('!! 校验失败 %d 条:' % len(bad))
