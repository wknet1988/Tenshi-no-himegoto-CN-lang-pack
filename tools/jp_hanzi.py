def sjis_safe(text):
    """True when every character encodes as a legal Shift-JIS pair."""
    i = 0
    data = text.encode('shift_jis', errors='replace')
    while i < len(data):
        b = data[i]
        if i + 1 < len(data):
            lead_ok = (0x81 <= b <= 0x9F) or (0xE0 <= b <= 0xFC)
            t = data[i + 1]
            trail_ok = (0x40 <= t <= 0x7E) or (0x80 <= t <= 0xFC)
            if lead_ok and trail_ok:
                i += 2
                continue
        i += 1
    return True


def convert(text):
    """Map each unsupported character to a Shift-JIS-representable glyph."""
    out = []
    unmapped = []
    for ch in text:
        try:
            b = ch.encode('cp932')
            if len(b) == 2:
                out.append(ch)
                continue
            raise UnicodeEncodeError('cp932', ch, 0, 1, 'single byte')
        except UnicodeEncodeError:
            rep = KANJI_MAP.get(ch)
            if rep:
                try:
                    rep.encode('cp932')
                    out.append(rep)
                    continue
                except UnicodeEncodeError:
                    pass
            unmapped.append(ch)
            out.append(ch)
    return ''.join(out), unmapped


